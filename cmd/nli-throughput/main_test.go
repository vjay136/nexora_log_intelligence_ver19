package main

import (
	"encoding/json"
	"os"
	"path/filepath"
	"testing"
)

func TestGenerateInputAndValidateJSONL(t *testing.T) {
	path := filepath.Join(t.TempDir(), "generated.jsonl")
	written, records, err := generateInput(path, 4096, 512)
	if err != nil {
		t.Fatal(err)
	}
	if written < 4096 || records < 1 {
		t.Fatalf("generated bytes=%d records=%d", written, records)
	}
	read, validRecords, invalid, oversized, err := validateJSONL(path, 1024)
	if err != nil {
		t.Fatal(err)
	}
	if read != written || validRecords != records || invalid != 0 || oversized != 0 {
		t.Fatalf("validation bytes=%d records=%d invalid=%d oversized=%d", read, validRecords, invalid, oversized)
	}
}

func TestValidateJSONLAccountsForInvalidOversizedAndFinalLine(t *testing.T) {
	path := filepath.Join(t.TempDir(), "mixed.jsonl")
	data := []byte("{\"ok\":true}\nnot-json\n{\"long\":\"12345678901234567890\"}\n{\"last\":true}")
	if err := os.WriteFile(path, data, 0o600); err != nil {
		t.Fatal(err)
	}
	read, records, invalid, oversized, err := validateJSONL(path, 20)
	if err != nil {
		t.Fatal(err)
	}
	if read != int64(len(data)) || records != 4 || invalid != 2 || oversized != 1 {
		t.Fatalf("bytes=%d records=%d invalid=%d oversized=%d", read, records, invalid, oversized)
	}
}

func TestCopyParserPacksAndValidateCheckpoints(t *testing.T) {
	dir := t.TempDir()
	source := filepath.Join(dir, "source")
	if err := os.Mkdir(source, 0o700); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(source, "one.json"), []byte(`{"id":"one"}`), 0o600); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(source, "ignored.txt"), []byte("ignored"), 0o600); err != nil {
		t.Fatal(err)
	}
	destination := filepath.Join(dir, "destination")
	if err := copyParserPacks(source, destination); err != nil {
		t.Fatal(err)
	}
	if _, err := os.Stat(filepath.Join(destination, "one.json")); err != nil {
		t.Fatal(err)
	}
	if _, err := os.Stat(filepath.Join(destination, "ignored.txt")); !os.IsNotExist(err) {
		t.Fatalf("non-JSON asset was copied: %v", err)
	}

	input := generatedInput{path: filepath.Join(dir, "input.log"), bytes: 12, records: 3}
	checkpointPath := filepath.Join(dir, "offsets.json")
	encoded, err := json.Marshal(map[string]savedCursor{input.path: {Offset: 12, Line: 3}})
	if err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(checkpointPath, encoded, 0o600); err != nil {
		t.Fatal(err)
	}
	files, bytes, records, err := validateCheckpoints(checkpointPath, []generatedInput{input})
	if err != nil || files != 1 || bytes != 12 || records != 3 {
		t.Fatalf("files=%d bytes=%d records=%d err=%v", files, bytes, records, err)
	}
	input.records = 4
	if _, _, _, err := validateCheckpoints(checkpointPath, []generatedInput{input}); err == nil {
		t.Fatal("expected checkpoint mismatch")
	}
}
